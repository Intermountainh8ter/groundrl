    if name != "DISCORD_SHORT.md":
        assert t["gc_ci"] in text and t["lora_r"] in text
        assert f"{t['hall_base']}% -> {t['hall_sft']}%" in text
        assert f"{t['base_abstain']}%" in text and f"{t['unanswerable_share']}%" in text
    if name in ("LINKEDIN.md", "FAQ.md"):
        assert t["hall_counts"] in text


