@pytest.mark.parametrize("name", LAUNCH)
def test_launch_copy_has_no_overclaims_and_no_stale_pre_training_claims(root, name):
    low = _flat(_launch_text(root, name)).lower()
    banned_phrases = ("state-of-the-art", "state of the art", "outperform", "we trained",
                      "our trained", "improves accuracy", "improved accuracy", "sota", "beats gpt",
                      "% better", "achieves", "breakthrough")
    for banned in banned_phrases:
        assert banned not in low, banned
    assert not re.search(r"\bbeat(s|ing)?\b", low)
    assert not re.search(r"trained (model|policy)[^.]{0,40}(reach|achiev|score)d?", low)
    # the copy was first written before any training; these claims are now false
    for stale in ("not yet run", "have not run", "has not been run", "never been run",
                  "no model has been trained", "nothing has been trained", "unrun",
                  "training: not"):
        assert stale not in low, stale
    # the GRPO run was degenerate: it must not be reported as working, failing or helping
    assert not re.search(r"\bgrpo (fails|failed|works|helps|helped|improves|improved)\b", low)
    assert not re.search(r"\bgrpo (does not|doesn't) (work|help)\b", low)
    assert not re.search(r"\brl (helps|helped|works|improves|improved|fails|failed)\b", low)


