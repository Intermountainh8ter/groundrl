def test_faq_leakage_claim_matches_the_task_files(root):
    def read_split(name):
        lines = (root / "data" / "tasks" / f"{name}.jsonl").read_text().splitlines()
        return [json.loads(line) for line in lines]

    def eips(tasks):
        return {e for t in tasks for e in t["eips"]}

    def fact_ids(tasks):
        return {f["id"] for t in tasks for f in t["gold_facts"]}

    train, test = read_split("train"), read_split("test")
    assert eips(train) and fact_ids(train)
    assert not eips(train) & eips(test) and not fact_ids(train) & fact_ids(test)
    assert "zero EIP overlap and zero fact-id overlap" in _flat(_launch_text(root, "FAQ.md"))


def test_launch_numbers_match_the_result_files(root):
    audit = json.loads((root / "results" / "audit_test.json").read_text())
    base = json.loads((root / "results" / "baseline_test.json").read_text())
    ext = base["policies"]["extractive"]["metrics"]["mean_reward"]["v2"]["mean"]
    top = max(p["scores"]["v2"]["mean"] for p in audit["policies"].values()
              if p["category"] != "reference")
    gold_free = len(audit["exploitable"]["v2-gold-free"])
    for name in LAUNCH:
        text = (root / "docs" / "launch" / name).read_text()
        assert "0.61" in text and round(ext, 2) == 0.61
        assert "0.44" in text and round(top, 2) == 0.44
        if "7 policies" in text or "7 of the policies" in text or "7 hacks" in text:
            assert gold_free == 7
    summary = json.loads((root / "data" / "tasks" / "SUMMARY.json").read_text())
    assert str(summary["total"]) in (root / "docs" / "launch" / "FAQ.md").read_text()


